    for i,step in enumerate(steps):step.setdefault('event',f'side/{id}/{i}')
    QUESTS.append(dict(id=id,type='side',title=title,auto_start=False,prerequisites=[],steps=steps,side_story=dict(owner=owner,min_index=minimum,chapter_bridge=True,description='章节调查：沿线核验线索并回访，完成后继续主线。无计时失败；错误判断可重新核验。',intro=L(intro),outro=L(outro),epilogue=L(epilogue),reward=dict(g=25,items={'water':1,'concentration_candy':1}))))
    GATES[gate]=id

