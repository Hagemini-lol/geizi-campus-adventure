from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def read(n):return json.loads((ROOT/n).read_text(encoding='utf-8-sig'))
def write(n,x):(ROOT/n).write_text(json.dumps(x,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def L(s):return [dict(actor=a.strip(),text=t.strip()) for a,t in (x.split('|',1) for x in s.strip().splitlines() if x.strip())]
def S(place,hint,text,**extra):return dict(location=place,hint=hint,dialogue=L(text),**extra)
def T(actor,hint,text,**extra):return dict(actor=actor,hint=hint,dialogue=L(text),**extra)
def P(question,right,wrong,resolve,retry):return dict(question=question,choices=[['right',right],['wrong',wrong],['cancel','暂时离开，稍后再查']],correct='right',resolution=L(resolve),retry=L(retry))
