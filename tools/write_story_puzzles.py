for q in data['tasks']:
    for i,s in enumerate(q['steps']):
        key=(q['id'],i)
        if key not in BOARDS:continue
        s['puzzle']=BOARDS[key]
        # A finite board replaces the former one-click correct/incorrect quiz.
        for field in ['question','choices','correct','resolution','retry']:s.pop(field,None)
(R/'任务配置.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
